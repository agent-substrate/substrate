// Package selfseccomp compiles and installs the worker seccomp-bpf filter from
// the per-architecture syscall tables generated by hack/selfseccomp.
package selfseccomp

import (
	"fmt"
	"slices"

	"golang.org/x/net/bpf"
	"golang.org/x/sys/unix"
)

var archAudit = map[string]uint32{
	"amd64": unix.AUDIT_ARCH_X86_64,
	"arm64": unix.AUDIT_ARCH_AARCH64,
}

var allowedSyscallsByArch = map[string][]uint32{
	"amd64": allowedSyscallsAMD64,
	"arm64": allowedSyscallsARM64,
}

var conditionalSyscallsByArch = map[string][]conditionalSyscall{
	"amd64": conditionalSyscallsAMD64,
	"arm64": conditionalSyscallsARM64,
}

type op int

const (
	opLessThan op = iota
	opEqual
)

func (o op) jumpTest() bpf.JumpTest {
	switch o {
	case opLessThan:
		return bpf.JumpLessThan
	case opEqual:
		return bpf.JumpEqual
	default:
		panic(fmt.Sprintf("unsupported seccomp op %d", o))
	}
}

type conditionalRule struct {
	Op    op
	Value uint32
}

type conditionalSyscall struct {
	Name  string
	Nr    uint32
	Rules []conditionalRule
}

const (
	retAllow = unix.SECCOMP_RET_ALLOW
	retDeny  = unix.SECCOMP_RET_ERRNO | uint32(unix.EPERM)
)

// compile builds the seccomp-bpf filter for goarch: kill on architecture
// mismatch, allow listed syscalls (with args[0] checks for conditional ones),
// and return EPERM for everything else.
func compile(goarch string) ([]unix.SockFilter, error) {
	insts, err := compileInstructions(goarch)
	if err != nil {
		return nil, err
	}
	raw, err := bpf.Assemble(insts)
	if err != nil {
		return nil, fmt.Errorf("assembling seccomp filter: %w", err)
	}
	filter := make([]unix.SockFilter, len(raw))
	for i, ri := range raw {
		filter[i] = unix.SockFilter{Code: ri.Op, Jt: ri.Jt, Jf: ri.Jf, K: ri.K}
	}
	return filter, nil
}

func compileInstructions(goarch string) ([]bpf.Instruction, error) {
	arch, ok := archAudit[goarch]
	if !ok {
		return nil, fmt.Errorf("no AUDIT_ARCH_* value for GOARCH=%s", goarch)
	}
	nums, ok := allowedSyscallsByArch[goarch]
	if !ok || len(nums) == 0 {
		return nil, fmt.Errorf("no allowed-syscall table for GOARCH=%s", goarch)
	}
	if !slices.IsSorted(nums) {
		return nil, fmt.Errorf("allowedSyscalls%s is not sorted", goarch)
	}

	b := &builder{}
	// Reject wrong architectures (including 32-bit/x32 compat ABIs).
	b.emit(bpf.LoadAbsolute{Off: 4, Size: 4}) // seccomp_data.arch
	b.emit(bpf.JumpIf{Cond: bpf.JumpEqual, Val: arch, SkipTrue: 1, SkipFalse: 0})
	b.emit(bpf.RetConstant{Val: unix.SECCOMP_RET_KILL_PROCESS})

	b.emit(bpf.LoadAbsolute{Off: 0, Size: 4}) // seccomp_data.nr
	for _, c := range conditionalSyscallsByArch[goarch] {
		b.buildConditionalDispatch(c)
	}

	b.buildAllowTree(nums)
	return b.insts, nil
}

type builder struct {
	insts []bpf.Instruction
}

func (b *builder) emit(i bpf.Instruction) int {
	b.insts = append(b.insts, i)
	return len(b.insts) - 1
}

// buildAllowTree emits a binary search over sorted syscall numbers. Conditional
// jumps stay within 0..1 instructions; only unconditional Jump (32-bit Skip)
// spans subtrees, avoiding classic BPF's 8-bit conditional jump limit.
func (b *builder) buildAllowTree(nums []uint32) {
	if len(nums) == 1 {
		b.emit(bpf.JumpIf{Cond: bpf.JumpEqual, Val: nums[0], SkipTrue: 0, SkipFalse: 1})
		b.emit(bpf.RetConstant{Val: retAllow})
		b.emit(bpf.RetConstant{Val: retDeny})
		return
	}
	mid := len(nums) / 2
	b.emit(bpf.JumpIf{Cond: bpf.JumpGreaterOrEqual, Val: nums[mid], SkipTrue: 0, SkipFalse: 1})
	jumpToUpper := b.emit(bpf.Jump{})
	b.buildAllowTree(nums[:mid])
	b.insts[jumpToUpper] = bpf.Jump{Skip: uint32(len(b.insts) - jumpToUpper - 1)}
	b.buildAllowTree(nums[mid:])
}

// buildConditionalDispatch handles a syscall allowed only for specific values
// of args[0]. If nr != c.Nr, it jumps past the block with A (nr) untouched.
func (b *builder) buildConditionalDispatch(c conditionalSyscall) {
	b.emit(bpf.JumpIf{Cond: bpf.JumpEqual, Val: c.Nr, SkipTrue: 1, SkipFalse: 0})
	skipBlock := b.emit(bpf.Jump{})
	blockStart := len(b.insts)

	// args[0] is a little-endian uint64 at offset 16 (low at 16, high at 20).
	// All rule values fit in uint32, so any nonzero high word cannot match.
	b.emit(bpf.LoadAbsolute{Off: 20, Size: 4})
	b.emit(bpf.JumpIf{Cond: bpf.JumpEqual, Val: 0, SkipTrue: 1, SkipFalse: 0})
	b.emit(bpf.RetConstant{Val: retDeny})

	b.emit(bpf.LoadAbsolute{Off: 16, Size: 4})
	for _, r := range c.Rules {
		b.emit(bpf.JumpIf{Cond: r.Op.jumpTest(), Val: r.Value, SkipTrue: 0, SkipFalse: 1})
		b.emit(bpf.RetConstant{Val: retAllow})
	}
	b.emit(bpf.RetConstant{Val: retDeny})

	b.insts[skipBlock] = bpf.Jump{Skip: uint32(len(b.insts) - blockStart)}
}
