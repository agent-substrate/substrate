# Copies the files that the substrate chart includes unchanged from
# manifests/ate-install: the data of the envoy router and egress gateway
# ConfigMaps, and the microVM SandboxConfig template. Writes to
# charts/substrate/files, or to the directory in $1.

set -o errexit -o nounset -o pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "${ROOT}"

OUT="${1:-charts/substrate/files}"
mkdir -p "${OUT}"

# Prints the data section of the ConfigMap in the manifest, unindented: the
# lines after "data:", up to the next document.
extract() {
  awk '
    /^---/ { configmap = 0; indata = 0; next }
    /^kind: ConfigMap$/ { configmap = 1 }
    configmap && /^data:$/ { indata = 1; next }
    indata { sub(/^  /, ""); print }
  ' "$1"
}

write() {
  {
    cat hack/boilerplate/sh.txt
    echo
    echo "# Code generated by hack/update/chart-files.sh from $1. DO NOT EDIT."
    extract "$1"
  } > "$2"
}

write manifests/ate-install/atenet-router.yaml "${OUT}/atenet-router-envoy-config.yaml"
write manifests/ate-install/atenet-egress.yaml "${OUT}/atenet-egress-envoy-config.yaml"
cp manifests/ate-install/sandboxconfig-microvm.yaml.tmpl "${OUT}/sandboxconfig-microvm.yaml.tmpl"
