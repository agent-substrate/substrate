set -o errexit -o nounset -o pipefail

# Renders each scenario in charts/scenarios, and writes the objects to
# rendered.yaml in the scenario directory. Each chart gets <chart>-values.yaml
# from the scenario directory when it exists, and its defaults otherwise. The
# substrate-crds chart is left out: hack/verify/chart-generated.sh checks the
# CRDs.

ROOT="$(git rev-parse --show-toplevel)"
cd "${ROOT}"

# render <scenario dir> <chart> <namespace>
render() {
  local values=()
  if [[ -f "${1}${2}-values.yaml" ]]; then
    values=(--values "${1}${2}-values.yaml")
  fi
  ./hack/run-tool.sh helm template "${2}" "charts/${2}" --namespace "${3}" ${values[@]+"${values[@]}"}
}

for dir in charts/scenarios/*/; do
  {
    cat hack/boilerplate/sh.txt
    echo
    echo "# Code generated by hack/update/chart-golden.sh. DO NOT EDIT."
    render "${dir}" substrate-podcert podcertificate-controller-system
    render "${dir}" substrate-atelet ate-system
    render "${dir}" substrate ate-system
  } > "${dir}rendered.yaml"
done
