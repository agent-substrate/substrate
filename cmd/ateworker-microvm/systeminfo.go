// System-info volume support for the micro-VM runtime.
//
// A system-info volume is a read-only directory of files generated by atelet
// on the host on every Run/Restore (e.g. the actorMetadata data-source files),
// so its contents always describe the actor actually being started, whatever
// checkpointed state it boots from. The host side is owned by atelet, which
// creates one directory per volume under
// ActorDirs.system_info_volume_roots_dir and wipes/rebuilds them when
// the actor's directories are reset.
//
// ateworker exposes that host directory to the guest under the single kataShared
// virtio-fs share at SharedDir(actorUID)/system-info, like durable-dir and CSI
// volumes — no extra virtio-fs device. Read-only is enforced twice: the host bind is
// remounted read-only (so nothing in the guest can write through the share),
// and each container bind adds "ro" (so the workload can't write the mount).
//
// Unlike durable-dir volumes, system-info volumes are deliberately absent
// from the checkpoint path: their contents must never be captured into
// snapshots (see the SystemInfo semantics in docs/api-guide.md). Regeneration
// is safe under find-paths migration because atelet rewrites the files at
// their stable share-relative paths before the share's virtiofsd starts.
// Trust bundles are also rewritten live at those same paths while virtiofsd
// serves the share; a stale guest reference to the replaced inode degrades
// to EIO (--migration-on-error=guest-error) rather than failing a restore.

package main

import (
	"context"
	"path/filepath"

	"go.ate.dev/substrate/cmd/ateworker-microvm/internal/kata"
	"go.ate.dev/substrate/internal/ocispec"
	"go.ate.dev/substrate/internal/proto/ateworkerpb"
)

// hasSystemInfoVolumes reports whether any container mounts a system-info
// volume.
func hasSystemInfoVolumes(containers []*ateworkerpb.Container) bool {
	for _, c := range containers {
		if len(c.GetSystemInfoVolumeMounts()) > 0 {
			return true
		}
	}
	return false
}

// stageSystemInfoVolumes exposes only explicitly requested whole-volume roots.
func (s *AteWorkerService) stageSystemInfoVolumes(ctx context.Context, actorUID, src string, names []string) error {
	for _, name := range names {
		if err := kata.BindIntoShare(ctx, filepath.Join(src, name), actorUID, filepath.Join(ocispec.ShareSystemInfo, name)); err != nil {
			return err
		}
		if err := kata.RemountReadOnly(filepath.Join(kata.SharedDir(actorUID), ocispec.ShareSystemInfo, name)); err != nil {
			return err
		}
	}
	return nil
}
